type I18nContextValue = {
  language: InterfaceLanguage;
  setLanguage: (language: InterfaceLanguage) => void;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
  translateLanguageName: (language: string | null | undefined) => string;
  getRouteTitle: (path: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function getInitialLanguage(): InterfaceLanguage {
  if (typeof window === 'undefined') return 'en';
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored === 'en' || stored === 'de') return stored;
  return window.navigator.language.toLowerCase().startsWith('de') ? 'de' : 'en';
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<InterfaceLanguage>(getInitialLanguage);

  useEffect(() => {
    document.documentElement.lang = language;
    window.localStorage.setItem(STORAGE_KEY, language);
  }, [language]);

  const value = useMemo<I18nContextValue>(() => {
    function t(key: TranslationKey, values?: Record<string, string | number>) {
      const entry = translations[language][key] ?? translations.en[key] ?? key;
      return typeof entry === 'function' ? entry(values) : entry;
    }

    return {
      language,
      setLanguage: setLanguageState,
      t,
      translateLanguageName(name) {
        if (!name) return t('common.notSet');
        const key = `language.${name}` as TranslationKey;
        return translations[language][key] ? t(key) : name;
      },
      getRouteTitle(path) {
        return t(routeTitleKeys[path] ?? 'title.home');
      },
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used inside LanguageProvider');
  }
  return context;
}
